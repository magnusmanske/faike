#!/usr/bin/env python3
"""Fetch a polite sample from Commons categories for detector benchmarking.

Writes downloads and an index.json (`{title: {path, extmetadata, ...}}`) that
`faike corpus` can evaluate. Use `--category` for both AI and negative sets:

  scripts/fetch-corpus.py --out /tmp/ai --per-category 20
  scripts/fetch-corpus.py --out /tmp/neg --per-category 15 \
      --category "Quality images" --category "Diagrams" \
      --category "Screenshots" --category "Photographs"
"""
import argparse
import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request

API = "https://commons.wikimedia.org/w/api.php"
UA = "faike-corpus/0.1 (https://www.mediawiki.org/wiki/User:Magnus_Manske; corpus testing)"

CATEGORIES = [
    "Images generated by Stable Diffusion",
    "Images generated by Adobe Firefly AI",
    "Images generated by ChatGPT",
    "Images generated by DALL-E",
    "Images generated by Midjourney",
    "Images generated by Flux (text-to-image model)",
    "Images generated by Imagen",
    "AI-generated images including prompts",
    "Images generated by Adobe Firefly AI",
    "Images generated by Meta AI",
]
IMAGE_EXT = (".jpg", ".jpeg", ".png", ".webp", ".gif", ".tif", ".tiff")


def get_json(params):
    params = dict(params, format="json", maxlag=5)
    url = API + "?" + urllib.parse.urlencode(params)
    for attempt in range(6):
        request = urllib.request.Request(url, headers={"User-Agent": UA})
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                data = json.load(response)
            if "error" in data:
                code = data["error"].get("code")
                if code == "maxlag":
                    time.sleep(5)
                    continue
                raise RuntimeError(data["error"])
            return data
        except urllib.error.HTTPError as error:
            if error.code in (429, 500, 502, 503, 504) and attempt < 5:
                wait = int(error.headers.get("Retry-After", "5"))
                print(f"  HTTP {error.code}; retrying in {wait}s", file=sys.stderr)
                time.sleep(wait)
                continue
            raise
    raise RuntimeError("too many retries")


def category_files(category, limit):
    data = get_json({
        "action": "query",
        "list": "categorymembers",
        "cmtitle": f"Category:{category}",
        "cmtype": "file",
        "cmlimit": limit,
    })
    return [m["title"] for m in data.get("query", {}).get("categorymembers", [])
            if m["title"].lower().endswith(IMAGE_EXT)]


def imageinfo(titles):
    data = get_json({
        "action": "query",
        "prop": "imageinfo",
        "iiprop": "url|size|mime|sha1|extmetadata",
        "iilimit": "1",
        "titles": "|".join(titles),
    })
    pages = data.get("query", {}).get("pages", {})
    out = {}
    for page in pages.values():
        info = (page.get("imageinfo") or [{}])[0]
        if info:
            out[page["title"]] = info
    return out


def safe_name(title):
    name = title.split(":", 1)[-1]
    return re.sub(r"[^A-Za-z0-9._-]+", "_", name)[:120]


def download(url, path):
    request = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(request, timeout=120) as response:
        with open(path, "wb") as handle:
            while True:
                chunk = response.read(1 << 20)
                if not chunk:
                    break
                handle.write(chunk)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--per-category", type=int, default=6)
    parser.add_argument("--max-bytes", type=int, default=20 * 1024 * 1024)
    parser.add_argument("--out", default="corpus")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--category", action="append", help="override the category list")
    parser.add_argument("--mime-prefix", default="image/")
    args = parser.parse_args()
    categories = args.category or CATEGORIES

    os.makedirs(args.out, exist_ok=True)
    index_path = os.path.join(args.out, "index.json")
    index = {}
    if args.resume and os.path.exists(index_path):
        with open(index_path) as handle:
            index = json.load(handle)

    for category in categories:
        print(f"== {category}")
        titles = category_files(category, 100)
        print(f"   {len(titles)} candidate files")
        picked = [t for t in titles if t not in index][: args.per_category]
        if not picked:
            continue
        time.sleep(1.5)
        infos = imageinfo(picked)
        for title in picked:
            info = infos.get(title)
            if not info:
                print(f"   skip {title}: no imageinfo")
                continue
            if not info.get("mime", "").startswith(args.mime_prefix):
                print(f"   skip {title}: {info.get('mime')}")
                continue
            if info.get("size", 0) > args.max_bytes:
                print(f"   skip {title}: {info.get('size')} bytes")
                continue
            folder = os.path.join(args.out, safe_name(category.replace(" ", "_")))
            os.makedirs(folder, exist_ok=True)
            path = os.path.join(folder, safe_name(title))
            if not (args.resume and os.path.exists(path)):
                time.sleep(1.5)
                try:
                    download(info["url"], path)
                except Exception as error:  # noqa: BLE001 - scratch tool
                    print(f"   download failed {title}: {error}", file=sys.stderr)
                    continue
            meta = info.get("extmetadata", {})
            index[title] = {
                "category": category,
                "path": path,
                "url": info.get("url"),
                "descriptionurl": info.get("descriptionurl"),
                "mime": info.get("mime"),
                "size": info.get("size"),
                "sha1": info.get("sha1"),
                "extmetadata": {
                    key: meta.get(key, {}).get("value")
                    for key in (
                        "LicenseShortName", "LicenseUrl", "Artist", "Credit",
                        "ImageDescription", "DateTimeOriginal", "Software",
                        "Categories", "UsageTerms",
                    )
                },
            }
            print(f"   saved {path}")
        with open(index_path, "w") as handle:
            json.dump(index, handle, indent=1, ensure_ascii=False)
    print(f"{len(index)} files indexed in {index_path}")


if __name__ == "__main__":
    main()
